const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={};vm.runInNewContext(fs.readFileSync('extension/input.js','utf8'),context);
const good={source:'instagram-export',account:'conta_exemplo',following:3,followers:1,users:['perfil_exemplo','perfil_exemplo'],protectedFollowers:['seguidor_exemplo']};
const result=context.validateLocalInput({...good,sessionid:'synthetic-do-not-store'});
assert.equal(result.users.length,1);assert.equal(result.sessionid,undefined);
assert.throws(()=>context.validateLocalInput({...good,account:'invalid/name'}));
assert.throws(()=>context.validateLocalInput({...good,followers:2}));
assert.throws(()=>context.validateLocalInput({...good,following:-1}));
assert.throws(()=>context.validateLocalInput({...good,users:['https://example.invalid/']}));
console.log('OK: importação válida, deduplicação, proteção consistente e descarte de campos desconhecidos.');
